import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { stringify } from "yaml";
import type { z } from "zod";
import { buildOpenApiDocument } from "@/lib/contract/openapi";
import { routes } from "@/lib/contract/routes";

const ROOT = resolve(import.meta.dirname, "../..");
const API_DIR = join(ROOT, "src/app/api");

function routeFile(path: string): string {
  return join(ROOT, "src/app", path.replace(/\{(\w+)\}/g, "[$1]"), "route.ts");
}

function listRouteFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) return listRouteFiles(p);
    return name === "route.ts" ? [p] : [];
  });
}

function isStrict(schema: z.ZodType): boolean {
  const def = (
    schema as unknown as { _zod: { def: { type: string; catchall?: { _zod: { def: { type: string } } } } } }
  )._zod.def;
  return def.type === "object" && def.catchall?._zod.def.type === "never";
}

describe("route contract", () => {
  const entries = Object.entries(routes);

  it("has a unique method and path for every route", () => {
    const keys = entries.map(([, r]) => `${r.method} ${r.path}`);
    expect(new Set(keys).size).toBe(keys.length);
  });

  for (const [id, r] of entries) {
    it(`${id}: ${r.method} ${r.path} is exported by its route file`, async () => {
      const file = routeFile(r.path);
      expect(existsSync(file), relative(ROOT, file)).toBe(true);
      const mod = (await import(file)) as Record<string, unknown>;
      expect(typeof mod[r.method]).toBe("function");
    });
  }

  it("has no route files or exported methods missing from the contract", async () => {
    const declared = new Set(entries.map(([, r]) => `${r.method} ${routeFile(r.path)}`));
    for (const file of listRouteFiles(API_DIR)) {
      const mod = (await import(file)) as Record<string, unknown>;
      for (const method of ["GET", "POST", "PATCH", "PUT", "DELETE"]) {
        if (mod[method])
          expect(declared.has(`${method} ${file}`), `${method} ${relative(ROOT, file)}`).toBe(true);
      }
    }
  });

  it("uses strict schemas for every params, query, and JSON body", () => {
    for (const [id, r] of entries) {
      if ("params" in r && r.params) expect(isStrict(r.params), `${id} params`).toBe(true);
      if ("query" in r && r.query) expect(isStrict(r.query), `${id} query`).toBe(true);
      if ("body" in r && r.body) expect(isStrict(r.body.schema), `${id} body`).toBe(true);
    }
  });

  it("requires auth on every route except health", () => {
    for (const [id, r] of entries) {
      if (id === "health") continue;
      expect(["user", "cron"], id).toContain(r.auth);
    }
    for (const [id, r] of entries.filter(([, r]) => r.path.startsWith("/api/internal/"))) {
      expect(r.auth, id).toBe("cron");
    }
  });

  it("declares 401 and 429 for every user route", () => {
    for (const [id, r] of entries.filter(([, r]) => r.auth === "user")) {
      expect(r.errors, id).toContain("unauthorized");
      expect(r.errors, id).toContain("rate_limited");
    }
  });
});

describe("OpenAPI document", () => {
  it("is in sync with docs/openapi.yaml (run `pnpm openapi`)", () => {
    const header = "# Generated by `pnpm openapi` from src/lib/contract. Do not edit by hand.\n";
    const expected = header + stringify(buildOpenApiDocument(), { lineWidth: 0 });
    expect(readFileSync(join(ROOT, "docs/openapi.yaml"), "utf8")).toBe(expected);
  });
});
