import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { stringify } from "yaml";
import { buildOpenApiDocument } from "../src/lib/contract/openapi";

const target = resolve(import.meta.dirname, "../docs/openapi.yaml");
const header = "# Generated by `pnpm openapi` from src/lib/contract. Do not edit by hand.\n";
const output = header + stringify(buildOpenApiDocument(), { lineWidth: 0 });

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // Missing file counts as out of date.
  }
  if (current !== output) {
    console.error("docs/openapi.yaml is out of date. Run `pnpm openapi`.");
    process.exit(1);
  }
  console.log("docs/openapi.yaml is up to date.");
} else {
  writeFileSync(target, output);
  console.log(`Wrote ${target}`);
}
